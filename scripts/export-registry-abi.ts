/**
 * Exports the compiled QuickPayRegistry ABI into the frontend as a typed const.
 * Run `forge build` first, then: bun run contracts:abi
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname } from 'node:path'

const artifactPath = 'contracts/out/QuickPayRegistry.sol/QuickPayRegistry.json'
const target = 'src/contracts/quickPayRegistryAbi.ts'

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8')) as { abi: unknown[] }
mkdirSync(dirname(target), { recursive: true })
writeFileSync(
  target,
  `// Generated by scripts/export-registry-abi.ts from the Foundry artifact. Do not edit by hand.\nexport const quickPayRegistryAbi = ${JSON.stringify(artifact.abi, null, 2)} as const\n`,
)
console.log(`Wrote ${target} (${artifact.abi.length} ABI entries)`)
